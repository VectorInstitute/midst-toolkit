"""Computes the Gower distance and membership signals between the challenge points
 and the synthetic data generated by the shadow models.
 Overall workflow and numerical decisions are taken with from CITADEL & UQAM team's attack implementation at
https://github.com/CRCHUM-CITADEL/ensemble-mia.
"""

from collections.abc import Sequence
from enum import Enum
from logging import INFO
from multiprocessing import Pool
from typing import Any, TypeAlias

import gower
import numpy as np
import pandas as pd

from midst_toolkit.common.logger import log


FloatDType: TypeAlias = type[np.float32] | type[np.float64]


class Key(Enum):
    TRAINED_RESULTS = "trained_results"
    FINE_TUNED_RESULTS = "fine_tuned_results"


def compute_gower_batched(
    df_x: pd.DataFrame,
    df_y: pd.DataFrame,
    cat_features: list[bool],
    batch_size: int,
    dtype: FloatDType,
) -> np.ndarray:
    """
    Compute Gower distance matrix in batches to reduce peak memory usage.

    This processes df_x in batches, computing distances against all of df_y,
    then stacks results.

    Args:
        df_x: First dataframe.
        df_y: Second dataframe.
        cat_features: A boolean list indicating which columns are categorical.
        batch_size: Number of rows from df_x to process in each batch.
        dtype: The data type to which numerical columns will be cast.

    Returns:
        Gower distance matrix as a numpy array.
    """
    n_x = len(df_x)
    n_y = len(df_y)

    # Pre-allocate output matrix
    gower_matrix = np.zeros((n_x, n_y), dtype=dtype)

    for start_idx in range(0, n_x, batch_size):
        end_idx = min(start_idx + batch_size, n_x)

        # Compute distance for this batch
        batch_matrix = gower.gower_matrix(
            data_x=df_x.iloc[start_idx:end_idx],
            data_y=df_y,
            cat_features=cat_features,
        )

        # Store in output matrix
        gower_matrix[start_idx:end_idx] = batch_matrix.astype(dtype)

    return gower_matrix


def compute_gower_for_model(
    args: tuple[
        int,
        pd.DataFrame,
        pd.DataFrame,
        int,
        str,
        int | None,
        list[bool],
        Sequence[str],
        FloatDType,
    ],
) -> tuple[int, np.ndarray]:
    """
    Computes the Gower distance matrix between df_input and a single synthetic dataframe.

    Args:
        args: A tuple containing:
            - i: Index of the model (for tracking purposes).
            - df_synthetic_raw: The synthetic dataframe generated by the shadow model.
            - df_input: The input dataframe to compare against.
            - min_length: Minimum length for downsampling.
            - id_column_name: Name of the ID column.
            - random_seed: Random seed for reproducibility.
            - categorical_features: A boolean list indicating which columns are categorical.
            - numerical_columns: List of numerical column names.
            - dtype: The data type to which numerical columns will be cast.

    Returns:
        A tuple containing:
            - i: Index of the model (same as input).
            - gower_matrix: The computed Gower distance matrix as a numpy array.
    """
    (
        i,
        df_synthetic_raw,
        df_input,
        min_length,
        id_column_name,
        random_seed,
        categorical_features,
        numerical_columns,
        dtype,
    ) = args

    df_synthetic = df_synthetic_raw.copy()

    # Convert numerical columns to float (otherwise error in the numpy divide)
    df_synthetic[numerical_columns] = df_synthetic[numerical_columns].astype(dtype)

    # Sample synthetic data points if there's too many
    if len(df_synthetic) > min_length:
        df_synthetic = df_synthetic.sample(n=min_length, random_state=random_seed)

    if id_column_name in df_synthetic.columns:
        df_synthetic = df_synthetic.drop(columns=[id_column_name])

    # Batched computation to reduce peak memory
    gower_matrix = compute_gower_batched(df_input, df_synthetic, categorical_features, batch_size=5000, dtype=dtype)

    return i, gower_matrix


def get_rmia_gower(
    df_input: pd.DataFrame,
    model_data: list[pd.DataFrame],
    min_length: int,
    categorical_column_names: list[str],
    id_column_name: str,
    random_seed: int | None = None,
    use_multiprocessing: bool = True,
    n_jobs: int = 4,
    dtype: FloatDType = np.float32,
) -> list[np.ndarray]:
    """
    Computes the Gower distance between the challenge points and the synthetic data generated by the shadow models.

    Args:
        df_input: The dataframe to generate features for (e.g., meta classifier train or test set), derived
            from the challenge dataset and processed in process_split_data.py.
        model_data: A list of dataframes, each representing the synthetic data generated by a shadow model.
        min_length: Minimum length across all training data, fine tuning data, and synthetic data sizes. This length
            will be used for downsampling to ensure consistent Gower distance calculations.
        categorical_column_names: A list of categorical column names. We assume that all other columns are numerical.
        id_column_name: Name of the ID column.
        random_seed: Random seed for reproducibility.
        use_multiprocessing: Whether to use multiprocessing for parallel computation of Gower distances.
        n_jobs: Number of parallel jobs to use for computation if ``use_multiprocessing`` is ``True``. Default is 4.
        dtype: The data type to which numerical columns will be cast for Gower distance computation. np.float32 is more
            memory efficient. Default is np.float32.

    Returns:
        A list of numpy arrays, each representing the Gower distance matrix between the input dataframe and the
        synthetic data from a model. Each entry in the list corresponds to one of the synthetically generated
        datasets provided within ``model_data``.

    """
    df_input = df_input.copy()
    # Check if any specified categorical columns are missing from the dataframe
    missing_categorical_columns = set(categorical_column_names) - set(df_input.columns)
    if missing_categorical_columns:
        log(
            INFO,
            f"Warning: The following categorical columns are missing from the dataframe, but have been passed as categorical columns: {missing_categorical_columns}. "
            "These columns will be ignored. Ensure that the specified categorical columns in your dataset's data_types.json file are in sync with the actual dataframe columns, unless it is intentional.",
        )

    categorical_features = [column in categorical_column_names for column in df_input.columns]

    # Defined the type as sequence to address mypy error.
    numerical_columns: Sequence[str] = [col for col in df_input.columns if col not in categorical_column_names]

    df_input[numerical_columns] = df_input[numerical_columns].astype(dtype)

    # Prepare arguments for each processing task
    args_list = [
        (
            i,
            df_synthetic,
            df_input,
            min_length,
            id_column_name,
            random_seed,
            categorical_features,
            numerical_columns,
            dtype,
        )
        for i, df_synthetic in enumerate(model_data)
    ]

    # Process in parallel or sequentially based on use_multiprocessing
    results = {}
    if use_multiprocessing:
        with Pool(processes=n_jobs) as pool:
            for i, gower_matrix in pool.imap_unordered(compute_gower_for_model, args_list):
                results[i] = gower_matrix
    else:
        for args in args_list:
            i, gower_matrix = compute_gower_for_model(args)
            results[i] = gower_matrix

    # Return in original order
    return [results[i] for i in range(len(model_data))]


def conditional_average(values: np.ndarray, condition_mask: np.ndarray) -> np.ndarray:
    """
    Calculate the conditional average of values based on a condition mask.
    This function computes the mean of the ``values`` array where the corresponding
    entries in the ``condition_mask`` are ``True``. If no entries satisfy the condition
    for a particular record, the result will be ``NaN`` for that record.

    Args:
        values: A NumPy array containing the values to average.
        condition_mask (numpy.ndarray): A boolean NumPy array of the same shape as
            ``values``, where ``True`` indicates the values to include in the average.

    Returns:
        An array of the same shape as the input, containing the conditional averages
        where the condition is met, or ``NaN`` where no values satisfy the condition.

    """
    assert values.shape == condition_mask.shape, "condition_mask must have the same shape as values"

    mask_sum = condition_mask.sum(axis=0)
    return np.where(mask_sum > 0, np.sum(values * condition_mask, axis=0) / mask_sum, np.nan)


def calculate_rmia_signals(
    df_input: pd.DataFrame,
    shadow_data_collection: list[dict[str, list[Any]]],
    target_synthetic_data: pd.DataFrame,
    categorical_column_names: list[str],
    id_column_name: str,
    id_column_data: pd.Series,
    k: int = 5,
    random_seed: int | None = None,
) -> pd.DataFrame:
    """
    Main orchestration function to compute Robust Membership Inference Attack (RMIA) signals
    with respect to shadow and target models.

    This function implements a data-based RMIA to determine the likelihood that a
    given data record was part of a target model's training set. The attack is
    data-based because it only uses synthetic data generated by the models, not the
    models themselves.

    The core idea is to compare a data record's similarity to two groups of synthetic data:
    1. Data generated by the 'target model' (the model we are simulating to attack).
    2. Data generated by several 'shadow models' (models trained on similar, but
       distinct, datasets).

    The intuition is that if a record was used to train the target model, the synthetic
    data it generates should be "closer" or more similar to that record than the
    synthetic data generated by the shadow models. This similarity is measured using
    Gower distance, which is suitable for datasets with mixed data types (both
    categorical and numerical).

    The final RMIA score is a ratio: (Similarity to Target Synthetic Data)/(Mean Similarity to Shadows Synthetic Data).
    A high RMIA score suggests that the record is disproportionately more similar to the
    target model's output, indicating a higher probability of being a training member.

    This implementation is based on how they used RMIA in this paper by Meeus et al.:
    https://arxiv.org/abs/2502.14921

    The original RMIA paper by Zarifzadeh et al. can be found at:
    https://arxiv.org/abs/2312.03262

    Args:
        df_input: The dataframe to generate features for (e.g., meta classifier train or test set), derived
            from the challenge dataset and processed in ``process_split_data.py``.
        shadow_data_collection: A list containing three dictionaries, each representing a collection of shadow
            models with their training data and generated synthetic outputs. Each collection can contain multiple
            shadow models. The first two dictionaries have keys ``fine_tuning_sets`` and ``fine_tuned_results``, while
            the third has keys ``selected_sets`` and ``trained_results``. The ``fine_tuning_sets`` and
            ``selected_sets`` keys map to lists of DataFrames containing the data IDs used to fine-tune or train
            the shadow models. The ``fine_tuned_results`` and ``trained_results`` keys map to lists of
            DataFrame objects, which store model generated synthetic data.
            See ``train_three_sets_of_shadow_models`` in ``attacks/ensemble/rmia/shadow_model_training.py``
            for additional details.
        target_synthetic_data: Target model's synthetic data as a DataFrame.
        categorical_column_names: A list of categorical column names.
        id_column_name: Name of the ID column.
        id_column_data: The data in the ID column extracted from df_input, ensuring that output signals are
            correctly aligned with their corresponding input records.
        k: The number of nearest neighbors to consider when computing the final membership inference signals.
            A higher ``k`` provides a more stable but less sensitive signal. Default is 5.
        random_seed: Random seed for reproducibility.

    Returns:
        A pandas DataFrame of shape (num_samples, 13) containing the following signals:
            - ``{id_column_name}``: The ID column for result alignment.
            - ``signal_shadow_k_1``: The smallest Gower distance from the input data to any shadow model's data
              (averaged across all shadow models). Lower is more similar.
            - ``signal_shadow_k_{k}``: The mean of the ``k`` smallest Gower distances from the
              input data to shadow models' data.
            - ``signal_shadows_in_k_1``: Smallest distance from the input data for records known to be IN the
              shadow models' training sets (a baseline for member behavior).
            - ``signal_shadows_in_k_{k}``: Mean of ``k`` smallest distances from the input data for IN records.
            - ``signal_shadows_out_k_1``: Smallest distance from the input data for records known to be OUT of
              the shadow models' training sets (a baseline for non-member behavior).
            - ``signal_shadows_out_k_{k}``: Mean of ``k`` smallest distances from the input data for OUT records.
            - ``signal_target_k_1``: The smallest Gower distance from the input data to the target model's data.
            - ``signal_target_k_{k}``: The mean of the ``k`` smallest Gower distances from the input data to the
              target model's data.
            - ``rmia_k_1``: The final RMIA score using the single nearest neighbor. A higher
              value indicates a stronger membership signal.
            - ``rmia_k_{k}``: The final RMIA score using ``k`` nearest neighbors.
            - ``rmia_out_k_1``: RMIA score calibrated against the 'OUT' shadow signals,
              providing a more robust measure of membership.
            - ``rmia_out_k_{k}``: RMIA score using ``k`` neighbors, calibrated against the
              'OUT' shadow signals.
    """
    # Extract shadow data collections. The first two elements are fine-tuned shadow models,
    # and the third element is the trained shadow models.

    fine_tuned_shadow_data_0 = shadow_data_collection[0]
    fine_tuned_shadow_data_1 = shadow_data_collection[1]
    trained_shadow_data = shadow_data_collection[2]

    all_lengths = [
        [len(data) for data in fine_tuned_shadow_data_0["fine_tuned_results"]],
        [len(data) for data in fine_tuned_shadow_data_1["fine_tuned_results"]],
        [len(data) for data in trained_shadow_data["trained_results"]],
        [len(data) for data in fine_tuned_shadow_data_0["fine_tuning_sets"]],
        [len(data) for data in fine_tuned_shadow_data_1["fine_tuning_sets"]],
        [len(data) for data in trained_shadow_data["selected_sets"]],
    ]

    # Validate lengths
    if any(len(group) == 0 for group in all_lengths):
        raise ValueError("shadow_data_collection/target_data contain empty sets; cannot compute RMIA.")

    min_length = min(min(group) for group in all_lengths)
    if not (1 <= k <= min_length):
        raise ValueError(f"k={k} must be within [1, {min_length}]")

    shadow_synthetic_list_0 = list(fine_tuned_shadow_data_0[Key.FINE_TUNED_RESULTS.value])
    shadow_model_gower_0 = get_rmia_gower(
        df_input=df_input,
        model_data=shadow_synthetic_list_0,
        min_length=min_length,
        categorical_column_names=categorical_column_names,
        id_column_name=id_column_name,
        random_seed=random_seed,
        n_jobs=4,
    )
    log(INFO, "Computed Gower distance for fine-tuned shadow models (first set of shadow models).")

    shadow_synthetic_list_1 = list(fine_tuned_shadow_data_1[Key.FINE_TUNED_RESULTS.value])

    shadow_model_gower_1 = get_rmia_gower(
        df_input=df_input,
        model_data=shadow_synthetic_list_1,
        min_length=min_length,
        categorical_column_names=categorical_column_names,
        id_column_name=id_column_name,
        random_seed=random_seed,
        n_jobs=4,
    )
    log(INFO, "Computed Gower distance for fine-tuned shadow models (second set of shadow models).")

    shadow_synthetic_list_2 = list(trained_shadow_data[Key.TRAINED_RESULTS.value])

    # shadow_synthetic_list_2 includes 8 shadow models
    shadow_model_gower_2 = get_rmia_gower(
        df_input=df_input,
        model_data=shadow_synthetic_list_2,
        min_length=min_length,
        categorical_column_names=categorical_column_names,
        id_column_name=id_column_name,
        random_seed=random_seed,
        n_jobs=4,
    )

    log(INFO, "Computed Gower distance for trained shadow models (third set of shadow models).")

    gower_shadows = np.vstack(
        [np.array(shadow_model_gower_0), np.array(shadow_model_gower_1), np.array(shadow_model_gower_2)]
    )

    # Process shadow model distances. Gower_shadows is a 3D matrix of shape:
    # ((total number of shadow models), len(df_input), len(shadow_synthetic))
    sorted_shadow_gower = np.sort(gower_shadows, axis=2)

    # TODO: check key after we have the official target model
    target_model_gower = get_rmia_gower(
        df_input=df_input,
        model_data=[target_synthetic_data],
        min_length=min_length,
        categorical_column_names=categorical_column_names,
        id_column_name=id_column_name,
    )

    log(INFO, "Computed Gower distance for the target model.")

    log(INFO, "Gower distance matrices computed...")
    # gower_target is a 2D NumPy array that stores the Gower distances between
    # the input data (df_input) and the synthetic data generated by the target model.
    # so its shape is (len(df_input), len(target_synthetic_data)).
    # gower_target[i, j] = Gower distance between i-th input record and j-th target synthetic record

    gower_target = target_model_gower[0]  # There is only one target model

    # Compute the signals based on the gower matrix wrt to the target synthetic data.
    # Here, for each input record, we sort the distances to all target synthetic records,
    # then keep only the first k columns (the k smallest distances).
    k_nearest_target_distances = np.sort(gower_target, axis=1)[:, :k]
    signal_target_k_mean = np.mean(k_nearest_target_distances, axis=1)
    signal_target_k_1 = gower_target[:, 0]  # First element is the minimum

    # TODO: ideally remove hard-copied keys
    shadow_training_data = (
        fine_tuned_shadow_data_0["fine_tuning_sets"]
        + fine_tuned_shadow_data_1["fine_tuning_sets"]
        + trained_shadow_data["selected_sets"]
    )

    # For k nearest neighbors
    # Similar to target, we sort the distances in each shadow model's gower matrix,
    # and keep only the first k columns (the k smallest distances).
    k_nearest_shadow_distances = sorted_shadow_gower[:, :, :k]
    signal_shadow_k_mean = np.mean(k_nearest_shadow_distances, axis=2)

    # Taking the mean across ALL shadow models (axis=0) to compute signal_shadows
    signal_shadows = np.mean(signal_shadow_k_mean, axis=0)

    # For single nearest neighbor (k=1)
    nearest_shadow_distances = sorted_shadow_gower[:, :, 0]
    # Taking the mean across all shadow models (axis=0) to compute k=1 signal for each input sample
    signal_shadows_k_1 = np.mean(nearest_shadow_distances, axis=0)

    # Create a dataframe for the computed scores
    results_df = pd.DataFrame(
        {
            id_column_name: id_column_data.values,
            "signal_shadow_k_1": signal_shadows_k_1,
            f"signal_shadow_k_{k}": signal_shadows,
        }
    )
    # Create masks for records in/out of training sets. We're creating masks for all the samples in train_df,
    # as opposed to the original implementation which only creates masks a sample of 200 records. We've also
    # changed the way the masks are created to improve efficiency.

    shadow_training_id_data = [set(id_list) for id_list in shadow_training_data]

    mask_in_training = np.array(
        [results_df[id_column_name].isin(id_set).to_numpy() for id_set in shadow_training_id_data]
    )

    mask_not_in_training = ~mask_in_training

    # Calculate signals based on membership status
    results_df["signal_shadows_in_k_1"] = conditional_average(nearest_shadow_distances, mask_in_training)
    results_df[f"signal_shadows_in_k_{k}"] = conditional_average(signal_shadow_k_mean, mask_in_training)
    results_df["signal_shadows_out_k_1"] = conditional_average(nearest_shadow_distances, mask_not_in_training)
    results_df[f"signal_shadows_out_k_{k}"] = conditional_average(signal_shadow_k_mean, mask_not_in_training)

    # Add target signals to results
    results_df["signal_target_k_1"] = signal_target_k_1
    results_df[f"signal_target_k_{k}"] = signal_target_k_mean

    # Calculate RMIA scores (ratios of target to shadow signals)
    results_df["rmia_k_1"] = np.divide(
        results_df["signal_target_k_1"],
        results_df["signal_shadow_k_1"],
        out=np.full_like(results_df["signal_target_k_1"], np.nan, dtype=float),
        where=results_df["signal_shadow_k_1"] > 0,
    )
    results_df[f"rmia_k_{k}"] = np.divide(
        results_df[f"signal_target_k_{k}"],
        results_df[f"signal_shadow_k_{k}"],
        out=np.full_like(results_df[f"signal_target_k_{k}"], np.nan, dtype=float),
        where=results_df[f"signal_shadow_k_{k}"] > 0,
    )
    results_df["rmia_out_k_1"] = np.divide(
        results_df["signal_target_k_1"],
        results_df["signal_shadows_out_k_1"],
        out=np.full_like(results_df["signal_target_k_1"], np.nan, dtype=float),
        where=results_df["signal_shadows_out_k_1"] > 0,
    )
    results_df[f"rmia_out_k_{k}"] = np.divide(
        results_df[f"signal_target_k_{k}"],
        results_df[f"signal_shadows_out_k_{k}"],
        out=np.full_like(results_df[f"signal_target_k_{k}"], np.nan, dtype=float),
        where=results_df[f"signal_shadows_out_k_{k}"] > 0,
    )

    return results_df
